// SHA-256 of a string's UTF-8 bytes, in plain TypeScript. The plugin bundles
// this package into an ES2020 script for Decaid's plugin host, which has no
// crypto API, and the management interface computes a Profile's id as it
// edits one, synchronously, so neither Node's `crypto` nor the browser's
// `SubtleCrypto` serves. Used for Decaid's profile id (profile.ts).

